export function icon(name, size = 24) {
  const span = document.createElement('span')
  span.className = 'ico'
  span.innerHTML = `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="currentColor" aria-hidden="true"><path d="${P[name] ?? ''}"/></svg>`
  return span
}

export function iconBtn(name, { title, onClick, size = 24, cls = '' } = {}) {
  const b = h('button', { class: 'ibtn ' + cls, title, 'aria-label': title, onClick }, icon(name, size))
  return b
}

export function toast(msg, ms = 3200) {
  let box = document.getElementById('toasts')
  if (!box) {
    box = h('div', { id: 'toasts' })
    document.body.append(box)
  }
  const t = h('div', { class: 'toast' }, msg)
  box.append(t)
  setTimeout(() => t.classList.add('out'), ms)
  setTimeout(() => t.remove(), ms + 300)
}

// Bottom sheet. items: [{label, sub, onClick, active}] or pass `content` element.
export function sheet({ title, items, content }) {
  const close = () => {
    root.classList.add('out')
    setTimeout(() => root.remove(), 200)
  }
  const body = content
    ? content
    : h(
        'div',
        { class: 'sheet-list' },
        (items ?? []).map((it) =>
          h(
            'button',
            {
              class: 'sheet-item' + (it.active ? ' active' : ''),
              onClick: () => {
                close()
                it.onClick?.()
              },
            },
            h('span', {}, it.label),
            it.sub ? h('small', {}, it.sub) : null,
          ),
        ),
      )
  const root = h(
    'div',
    { class: 'sheet-root', onClick: (e) => e.target === root && close() },
    h('div', { class: 'sheet' }, h('div', { class: 'sheet-title' }, title ?? ''), body),
  )
  document.body.append(root)
  return close
}

export const fmtTime = (ms) => {
  const s = Math.max(0, Math.floor(ms / 1000))
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`
}

// Pick an image close to the wanted width.
export function pickImage(images, want = 300) {
  if (!images?.length) return ''
  const sorted = [...images].sort((a, b) => (a.width ?? 0) - (b.width ?? 0))
  return (sorted.find((i) => (i.width ?? 9999) >= want) ?? sorted[sorted.length - 1]).url
}

